"""
Parser for MosMeridian WinOrient "Result list" HTML pages.

These pages are generated by WinOrient software, encoded in Windows-1251.

Page structure:
  <h1>  — event name, e.g. "Московский Меридиан"
  <h2>  — course info per distance, e.g. "1, 22 КП, 6.880 м"
  <pre> — one per distance (course), containing:
    <u><b>  — column header with CP codes: "1( 35)  2( 50)..."
    per athlete:
      plain text line  — pos name club qual bib year HH:MM:SS place note  leg1(r) leg2(r)...
      <u>              — cumulative splits:   cum1(r)  cum2(r) ...  (M:SS format, by CP order)

Differences from o-mephi.net format:
  - Cumulative times are M:SS (not HH:MM:SS), with no CP code embedded.
  - Bib numbers can be 2-5 digits (not always 4+).
  - H2 contains "N, M КП, X м" (course number, CP count, climb) not class name.

Classes are derived from athlete birth year + gender detected from Russian name.
"""
import re
from dataclasses import dataclass, field
from html.parser import HTMLParser
from typing import Optional


# ── Data structures ───────────────────────────────────────────────────────────

@dataclass
class SplitEntry:
    control_point: str       # CP code, e.g. "35"
    cumulative_time_ms: int


@dataclass
class AthleteData:
    position: Optional[int]
    last_name: str
    first_name: str
    club: str
    qualification: str
    bib_number: str
    birth_year: Optional[int]
    time_ms: Optional[int]
    status: str              # 'ok' | 'dnf' | 'dns' | 'dsq'
    competition_class: str
    splits: list[SplitEntry] = field(default_factory=list)

    @property
    def full_name(self) -> str:
        return f'{self.last_name} {self.first_name}'.strip()


@dataclass
class ClassData:
    name: str                # e.g. "D1", "D2", "D3"
    distance_meters: Optional[int]
    control_points: list[str] = field(default_factory=list)
    athletes: list[AthleteData] = field(default_factory=list)


@dataclass
class CompetitionData:
    title: str
    date: str        # ISO date string, e.g. "2026-04-02"
    location: str
    classes: list[ClassData] = field(default_factory=list)


# ── Gender detection & age class ─────────────────────────────────────────────

# Russian female last names almost always end in 'а' or 'я' (after declension).
# Male names end in consonants, 'й', 'и', 'у' etc.
_FEMALE_LAST_SUFFIXES = ('а', 'я')
# Known male names ending in 'а'/'я' (exceptions)
_MALE_EXCEPTION_FIRST = frozenset({'илья', 'никита', 'данила', 'кузьма', 'фома', 'лука'})

# Весенний сезон ММ uses МЖ 10,12,14,16,18,20,21,35,40,45,50,55,60,65,70,75
_AGE_THRESHOLDS = [75, 70, 65, 60, 55, 50, 45, 40, 35, 21, 20, 18, 16, 14, 12, 10]

# Placeholder names to skip (rental chips, reserved slots)
_SKIP_NAMES = frozenset({'аренда мм', 'резерв'})


def _is_female(last_name: str, first_name: str) -> bool:
    """Heuristic gender detection for Russian names."""
    last = last_name.strip().lower()
    first = first_name.strip().lower()
    if first in _MALE_EXCEPTION_FIRST:
        return False
    if last.endswith(_FEMALE_LAST_SUFFIXES):
        return True
    if first.endswith(('а', 'я', 'ь')) and first not in _MALE_EXCEPTION_FIRST:
        return True
    return False


def age_class(birth_year: int, female: bool, competition_year: int) -> str:
    """Derive Russian orienteering age class, e.g. 'М21', 'Ж35'."""
    age = competition_year - birth_year
    prefix = 'Ж' if female else 'М'
    for threshold in _AGE_THRESHOLDS:
        if age >= threshold:
            return f'{prefix}{threshold}'
    return f'{prefix}10'


def is_placeholder(last_name: str, first_name: str) -> bool:
    """True for 'аренда ММ', 'резерв' etc. entries that have no real athlete."""
    combined = f'{last_name} {first_name}'.strip().lower()
    return combined in _SKIP_NAMES or last_name.strip().lower() in _SKIP_NAMES


# ── Helpers ───────────────────────────────────────────────────────────────────

def _finish_time_to_ms(s: str) -> Optional[int]:
    """Parse HH:MM:SS → milliseconds."""
    m = re.match(r'(\d+):(\d{2}):(\d{2})', s)
    if not m:
        return None
    return (int(m.group(1)) * 3600 + int(m.group(2)) * 60 + int(m.group(3))) * 1000


def _split_time_to_ms(s: str) -> Optional[int]:
    """Parse M:SS or MM:SS → milliseconds (cumulative split format)."""
    m = re.match(r'^(\d{1,2}):(\d{2})$', s.strip())
    if not m:
        return None
    return (int(m.group(1)) * 60 + int(m.group(2))) * 1000


def _extract_cps(line: str) -> list[str]:
    """Extract ordered CP codes from header like '1( 35)  2( 50)...' → ['35','50',...]"""
    return re.findall(r'\d+\(\s*(\d+)\s*\)', line)


def _parse_cumulative_splits(cum_line: str, cp_codes: list[str]) -> list[SplitEntry]:
    """
    Build cumulative SplitEntry list from the <u> row.
    Times are in M:SS(rank) format; matched to CP codes by order.
    """
    matches = re.findall(r'(\d{1,2}:\d{2})\(\s*\d+\s*\)', cum_line)
    result = []
    for i, t_str in enumerate(matches):
        if i >= len(cp_codes):
            break
        ms = _split_time_to_ms(t_str)
        if ms is not None:
            result.append(SplitEntry(cp_codes[i], ms))
    return result


# ── Athlete line regex ────────────────────────────────────────────────────────
# Columns (WinOrient fixed-width result list):
#   pos(1-4)  name(26)  club(21)  qual(0-6)  bib(2-5)  year(4)  result(HH:MM:SS)
_ATHLETE_RE = re.compile(
    r'^\s{1,4}(\d+)\s'    # position
    r'(.{26})'             # name (26 chars fixed)
    r'(.{21})'             # club (21 chars fixed)
    r'(.{0,6}?)\s+'        # qualification (0-6 chars, flexible)
    r'(\d{2,5})\s+'        # bib number (2-5 digits)
    r'(\d{4})\s+'          # birth year
    r'(\S+)'               # result: HH:MM:SS or WinOrient status code
)

_STATUS_CODES = {
    '3.13.12.2': 'dnf',
    '3.13.12.1': 'dns',
    '3.13.2.1':  'dsq',
    '3.13.3.1':  'dsq',
}


def _parse_athlete_line(
    line: str,
    distance_name: str,
    competition_year: int,
) -> Optional[AthleteData]:
    """
    Parse a single athlete result line.

    competition_class is derived from gender + birth_year.
    If birth_year is missing (rental chip, etc.) competition_class falls back to distance_name.
    """
    m = _ATHLETE_RE.match(line)
    if not m:
        return None

    pos = int(m.group(1))
    name = m.group(2).strip()
    club = m.group(3).strip()
    qual = m.group(4).strip()
    bib = m.group(5).strip()
    year_str = m.group(6)
    result_str = m.group(7)

    birth_year = int(year_str) if year_str.isdigit() else None

    if re.match(r'^\d{2}:\d{2}:\d{2}$', result_str):
        status = 'ok'
        time_ms = _finish_time_to_ms(result_str)
    else:
        status = _STATUS_CODES.get(result_str, 'dnf')
        time_ms = None

    # WinOrient "LASTNAME Firstname" convention
    parts = name.split(None, 1)
    last_name = parts[0] if parts else name
    first_name = parts[1] if len(parts) > 1 else ''

    # Skip placeholder entries
    if is_placeholder(last_name, first_name):
        return None

    # Derive class from gender + age
    if birth_year:
        female = _is_female(last_name, first_name)
        comp_class = age_class(birth_year, female, competition_year)
    else:
        comp_class = distance_name  # fallback for unknown birth year

    return AthleteData(
        position=pos,
        last_name=last_name,
        first_name=first_name,
        club=club,
        qualification=qual,
        bib_number=bib,
        birth_year=birth_year,
        time_ms=time_ms,
        status=status,
        competition_class=comp_class,
    )


# ── HTML parser ───────────────────────────────────────────────────────────────

class _MosmeridianHTMLParser(HTMLParser):
    """
    State-machine parser for MosMeridian WinOrient result list pages.

    Identical flow to the o-mephi parser but adapted for:
    - h1 → event title (quoted event name)
    - h2 → class info "N, M КП, X м" → class name "DN"
    - <u> inside pre: first = CP header (with <b> inside); subsequent = cumulative splits
    - cumulative split format: M:SS(rank) — no CP code, matched by order
    """

    def __init__(self, competition_year: int = 2026):
        super().__init__()
        self.competition = CompetitionData(title='', date='', location='')
        self._competition_year = competition_year

        self._in_pre = False
        self._in_h1 = False
        self._in_h2 = False
        self._in_u = False

        self._h1_buf: list[str] = []
        self._h2_buf: list[str] = []
        self._parts: list[str] = []
        self._pre_items: list[tuple[str, str]] = []   # ('athlete' | 'cumulative', text)
        self._current_class: Optional[ClassData] = None

    def handle_starttag(self, tag, attrs):
        if tag == 'h1':
            self._in_h1 = True
        elif tag == 'h2':
            self._in_h2 = True
        elif tag == 'pre':
            self._in_pre = True
            self._parts = []
            self._pre_items = []
        elif tag == 'u' and self._in_pre:
            self._flush_athlete()
            self._in_u = True

    def handle_endtag(self, tag):
        if tag == 'h1':
            self._in_h1 = False
            self._process_h1(''.join(self._h1_buf))
            self._h1_buf = []
        elif tag == 'h2':
            self._in_h2 = False
            self._process_h2(''.join(self._h2_buf))
            self._h2_buf = []
        elif tag == 'pre':
            self._flush_athlete()
            self._process_pre()
            self._in_pre = False
        elif tag == 'u' and self._in_pre:
            text = ''.join(self._parts)
            if text.strip():
                self._pre_items.append(('cumulative', text))
            self._parts = []
            self._in_u = False

    def handle_data(self, data):
        if self._in_h1:
            self._h1_buf.append(data)
        elif self._in_h2:
            self._h2_buf.append(data)
        elif self._in_pre:
            self._parts.append(data)

    # ── internal processing ───────────────────────────────────────────────────

    def _flush_athlete(self):
        text = ''.join(self._parts)
        if text.strip():
            self._pre_items.append(('athlete', text))
        self._parts = []

    def _process_h1(self, text: str):
        """Extract event name from h1 like '"Московский Меридиан"__...'."""
        m = re.search(r'"([^"]{3,})"', text)
        if m:
            self.competition.title = m.group(1).strip()
        elif text.strip():
            self.competition.title = text.strip().split('\n')[0].strip()

    def _process_h2(self, text: str):
        """Parse course header like '1, 22 КП, 6.880 м' → ClassData."""
        text = text.strip()
        if not text:
            return
        m = re.match(r'^(\d+),', text)
        if not m:
            return
        class_name = f'D{m.group(1)}'
        self._current_class = ClassData(name=class_name, distance_meters=None)
        self.competition.classes.append(self._current_class)

    def _process_pre(self):
        """Process all (athlete, cumulative) items from one <pre> block."""
        if not self._current_class or not self._pre_items:
            return

        header_seen = False
        pending_athlete: Optional[AthleteData] = None

        for kind, text in self._pre_items:
            if kind == 'cumulative':
                if not header_seen:
                    # First cumulative item (inside <u><b>) = CP header
                    self._current_class.control_points = _extract_cps(text)
                    header_seen = True
                else:
                    # Cumulative split row for the preceding athlete
                    if pending_athlete is not None:
                        if pending_athlete.status == 'ok':
                            pending_athlete.splits = _parse_cumulative_splits(
                                text, self._current_class.control_points
                            )
                        self._current_class.athletes.append(pending_athlete)
                        pending_athlete = None
            else:
                # Athlete text block — may span multiple raw lines
                if pending_athlete is not None:
                    # Previous athlete had no cumulative row (no finish time or DNS)
                    self._current_class.athletes.append(pending_athlete)
                    pending_athlete = None
                for raw_line in text.splitlines():
                    if raw_line.strip():
                        parsed = _parse_athlete_line(
                            raw_line,
                            self._current_class.name,
                            self._competition_year,
                        )
                        if parsed:
                            pending_athlete = parsed
                        break

        if pending_athlete is not None:
            self._current_class.athletes.append(pending_athlete)


# ── Public API ────────────────────────────────────────────────────────────────

def parse_results_html(html: 'bytes | str', date: str, location: str = '', competition_year: int = 2026) -> CompetitionData:
    """
    Parse a WinOrient result-list HTML page.

    Args:
        html:     Raw page bytes (Windows-1251) or decoded string.
        date:     ISO date string for this competition, e.g. "2026-04-02".
        location: Optional location string.
    """
    if isinstance(html, bytes):
        text = html.decode('windows-1251', errors='replace')
    else:
        text = html

    parser = _MosmeridianHTMLParser(competition_year=competition_year)
    parser.feed(text)

    comp = parser.competition
    comp.date = date
    comp.location = location
    return comp


def fetch_and_parse(url: str, date: str, location: str = '', competition_year: int = 2026) -> CompetitionData:
    """Fetch a result-list page URL and parse it."""
    import urllib.request
    with urllib.request.urlopen(url) as resp:
        html_bytes = resp.read()
    return parse_results_html(html_bytes, date=date, location=location, competition_year=competition_year)
