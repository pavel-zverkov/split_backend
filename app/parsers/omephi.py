"""
Parser for o-mephi.net WinOrient HTML result/split pages.

These pages are generated by WinOrient software and encoded in Windows-1251.
Each page contains per-class sections with athlete results and split times.

Split page format (inside <pre> per class):
  - Header line (<u><b>): column labels + CP codes like "1( 67)  1( 66)..."
  - Per athlete:
      - Result line: pos name(26) club(21) qual(4) bib(4+) year(4) time delta place [split_times...]
      - Cumulative line (<u>): cumulative_time(cp_code)(rank) per CP
"""
import re
from dataclasses import dataclass, field
from html.parser import HTMLParser
from typing import Optional


# ── Transliteration ──────────────────────────────────────────────────────────

_TRANSLIT = {
    'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ё': 'yo',
    'ж': 'zh', 'з': 'z', 'и': 'i', 'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm',
    'н': 'n', 'о': 'o', 'п': 'p', 'р': 'r', 'с': 's', 'т': 't', 'у': 'u',
    'ф': 'f', 'х': 'kh', 'ц': 'ts', 'ч': 'ch', 'ш': 'sh', 'щ': 'sch',
    'ъ': '', 'ы': 'y', 'ь': '', 'э': 'e', 'ю': 'yu', 'я': 'ya',
}
_TRANSLIT.update({k.upper(): v for k, v in _TRANSLIT.items()})


def transliterate(text: str) -> str:
    return ''.join(_TRANSLIT.get(c, c) for c in text)


# ── Data structures ───────────────────────────────────────────────────────────

@dataclass
class SplitEntry:
    control_point: str   # CP code as string, e.g. "67"
    cumulative_time_ms: int


@dataclass
class AthleteData:
    position: Optional[int]
    last_name: str
    first_name: str
    club: str
    qualification: str
    bib_number: str
    birth_year: Optional[int]
    time_ms: Optional[int]
    status: str            # 'ok' | 'dnf' | 'dns' | 'dsq'
    competition_class: str
    splits: list[SplitEntry] = field(default_factory=list)

    @property
    def full_name(self) -> str:
        return f'{self.last_name} {self.first_name}'.strip()


@dataclass
class ClassData:
    name: str
    distance_meters: Optional[int]
    control_points: list[str] = field(default_factory=list)   # ordered CP codes
    athletes: list[AthleteData] = field(default_factory=list)


@dataclass
class CompetitionData:
    title: str
    date: str        # ISO date string, e.g. "2026-03-08"
    location: str
    classes: list[ClassData] = field(default_factory=list)


# ── Helpers ───────────────────────────────────────────────────────────────────

def _time_to_ms(time_str: str) -> Optional[int]:
    """Parse HH:MM:SS → milliseconds."""
    m = re.match(r'(\d+):(\d{2}):(\d{2})', time_str.strip())
    if not m:
        return None
    h, mi, s = int(m.group(1)), int(m.group(2)), int(m.group(3))
    return (h * 3600 + mi * 60 + s) * 1000


def _parse_km(text: str) -> Optional[int]:
    """Parse '1,7 км' or '2.2 km' → meters."""
    m = re.search(r'(\d+)[,.](\d+)', text)
    if not m:
        return None
    whole = int(m.group(1))
    frac_str = m.group(2)
    # Treat first digit of fraction as tenths of km = hundreds of metres
    frac = int(frac_str[0]) * 100
    return whole * 1000 + frac


def _extract_cps(header_text: str) -> list[str]:
    """Extract ordered CP codes from header line: '1( 67)  1( 66)...' → ['67','66',...]"""
    return re.findall(r'\(\s*(\d+)\)', header_text)


def _parse_cumulative_splits(cum_line: str) -> list[SplitEntry]:
    """Extract cumulative split entries from the underline row."""
    entries = []
    for m in re.finditer(r'(\d{2}:\d{2}:\d{2})\(\s*(\d+)\)\(\s*\d+\)', cum_line):
        t = _time_to_ms(m.group(1))
        if t is not None:
            entries.append(SplitEntry(control_point=m.group(2).strip(), cumulative_time_ms=t))
    return entries


# ── Fixed-width athlete line regex ────────────────────────────────────────────
# Columns: pos(4) space(1) name(26) club(21) qual(4) space bib(4-5) space year(4) space result...
_ATHLETE_RE = re.compile(
    r'^\s{1,4}(\d+)\s'   # position (right-padded, 1-4 spaces before)
    r'(.{26})'            # name  (26 chars fixed)
    r'(.{21})'            # club  (21 chars fixed)
    r'(.{0,6}?)\s+'       # qualification (flexible, typically 0-5 chars)
    r'(\d{4,5})\s+'       # bib number
    r'(\d{4})\s+'         # birth year
    r'(\S+)'              # result: HH:MM:SS or status code like 3.13.12.2
)

# WinOrient DNF/DNS/DSQ codes
_STATUS_CODES = {
    '3.13.12.2': 'dnf',
    '3.13.12.1': 'dns',
    '3.13.2.1':  'dsq',
    '3.13.3.1':  'dsq',
}


def _parse_athlete_line(line: str, competition_class: str) -> Optional[AthleteData]:
    m = _ATHLETE_RE.match(line)
    if not m:
        return None

    pos = int(m.group(1))
    name = m.group(2).strip()
    club = m.group(3).strip()
    qual = m.group(4).strip()
    bib = m.group(5).strip()
    year_str = m.group(6)
    result_str = m.group(7)

    birth_year = int(year_str) if year_str.isdigit() else None

    # Determine status
    if re.match(r'^\d{2}:\d{2}:\d{2}$', result_str):
        status = 'ok'
        time_ms = _time_to_ms(result_str)
    else:
        status = _STATUS_CODES.get(result_str, 'dnf')
        time_ms = None

    # Split name into last/first (WinOrient: "Фамилия Имя [Отчество]")
    parts = name.split(None, 1)
    last_name = parts[0] if parts else name
    first_name = parts[1] if len(parts) > 1 else ''

    return AthleteData(
        position=pos,
        last_name=last_name,
        first_name=first_name,
        club=club,
        qualification=qual,
        bib_number=bib,
        birth_year=birth_year,
        time_ms=time_ms,
        status=status,
        competition_class=competition_class,
    )


# ── HTML parser ───────────────────────────────────────────────────────────────

class _OmephiHTMLParser(HTMLParser):
    """
    State-machine parser for WinOrient HTML pages from o-mephi.net.

    Within each <pre> block:
      - First <u> line is the header (CP codes).
      - Athlete text lines accumulate in _parts between <u> boundaries.
      - Each <u> line after the header holds cumulative splits for the previous athlete.
    """

    def __init__(self):
        super().__init__()
        self.competition = CompetitionData(title='', date='', location='')

        self._in_pre = False
        self._in_h2 = False
        self._in_h1 = False
        self._in_u = False

        self._h1_buf: list[str] = []
        self._h2_buf: list[str] = []

        # Per-<pre> state
        self._parts: list[str] = []       # fragments of current "athlete" line
        self._pre_items: list[tuple[str, str]] = []   # ('athlete'|'cumulative', text)
        self._current_class: Optional[ClassData] = None

    # ── tag handlers ─────────────────────────────────────────────────────────

    def handle_starttag(self, tag, attrs):
        if tag == 'h1':
            self._in_h1 = True
        elif tag == 'h2':
            self._in_h2 = True
        elif tag == 'pre':
            self._in_pre = True
            self._parts = []
            self._pre_items = []
        elif tag == 'u' and self._in_pre:
            self._flush_athlete()
            self._in_u = True

    def handle_endtag(self, tag):
        if tag == 'h1':
            self._in_h1 = False
            self._process_h1(''.join(self._h1_buf))
            self._h1_buf = []
        elif tag == 'h2':
            self._in_h2 = False
            self._process_h2(''.join(self._h2_buf))
            self._h2_buf = []
        elif tag == 'pre':
            self._flush_athlete()
            self._process_pre()
            self._in_pre = False
        elif tag == 'u' and self._in_pre:
            # flush cumulative line
            text = ''.join(self._parts)
            if text.strip():
                self._pre_items.append(('cumulative', text))
            self._parts = []
            self._in_u = False

    def handle_data(self, data):
        if self._in_h1:
            self._h1_buf.append(data)
        elif self._in_h2:
            self._h2_buf.append(data)
        elif self._in_pre:
            self._parts.append(data)

    # ── internal processing ───────────────────────────────────────────────────

    def _flush_athlete(self):
        """Flush accumulated text as an athlete line."""
        text = ''.join(self._parts)
        if text.strip():
            self._pre_items.append(('athlete', text))
        self._parts = []

    def _process_h1(self, text: str):
        lines = [l.strip() for l in text.splitlines() if l.strip()]
        if lines:
            self.competition.title = lines[0]
        for line in lines:
            # Date pattern: "08 марта 2026, Борисово-Городня"
            dm = re.search(r'(\d{2})\s+\S+\s+(\d{4})', line)
            if dm:
                day = int(dm.group(1))
                year = int(dm.group(2))
                # Month from Russian month names
                month_map = {
                    'января': 1, 'февраля': 2, 'марта': 3, 'апреля': 4,
                    'мая': 5, 'июня': 6, 'июля': 7, 'августа': 8,
                    'сентября': 9, 'октября': 10, 'ноября': 11, 'декабря': 12,
                }
                for rus, num in month_map.items():
                    if rus in line.lower():
                        self.competition.date = f'{year}-{num:02d}-{day:02d}'
                        break
                # Location after comma
                if ',' in line:
                    self.competition.location = line.split(',', 1)[1].strip()

    def _process_h2(self, text: str):
        """Parse class header like 'Ж08, 12 КП, 1,7 км'."""
        text = text.strip()
        if not text:
            return
        parts = text.split(',')
        class_name = parts[0].strip()
        # Distance: look for "N,M км" pattern
        distance_m = None
        for part in parts:
            if 'км' in part.lower() or 'km' in part.lower():
                distance_m = _parse_km(part)
                break
        self._current_class = ClassData(
            name=class_name,
            distance_meters=distance_m,
        )

        self.competition.classes.append(self._current_class)

    def _process_pre(self):
        """Process all lines collected from a <pre> block."""
        if not self._current_class or not self._pre_items:
            return

        header_seen = False
        pending_athlete: Optional[AthleteData] = None

        for kind, text in self._pre_items:
            if kind == 'cumulative':
                if not header_seen:
                    # First cumulative item = header with CP codes
                    self._current_class.control_points = _extract_cps(text)
                    header_seen = True
                else:
                    # Cumulative splits for the preceding athlete
                    if pending_athlete is not None:
                        pending_athlete.splits = _parse_cumulative_splits(text)
                        self._current_class.athletes.append(pending_athlete)
                        pending_athlete = None
            else:
                # Athlete line — may contain multiple raw lines; take the first non-empty one.
                if pending_athlete is not None:
                    # Previous athlete had no cumulative line (e.g. DNS)
                    self._current_class.athletes.append(pending_athlete)
                    pending_athlete = None
                for raw_line in text.splitlines():
                    if raw_line.strip():
                        parsed = _parse_athlete_line(
                            raw_line, self._current_class.name
                        )
                        if parsed:
                            pending_athlete = parsed
                        break

        if pending_athlete is not None:
            self._current_class.athletes.append(pending_athlete)


def parse_splits_html(html: 'bytes | str') -> CompetitionData:
    """
    Parse a WinOrient splits HTML page.

    Accepts either windows-1251 encoded bytes (as returned by urllib/requests)
    or an already-decoded str.
    """
    if isinstance(html, bytes):
        text = html.decode('windows-1251', errors='replace')
    else:
        text = html
    parser = _OmephiHTMLParser()
    parser.feed(text)
    return parser.competition


def fetch_and_parse(url: str) -> CompetitionData:
    """Fetch a splits page URL and parse it."""
    import urllib.request
    with urllib.request.urlopen(url) as resp:
        html_bytes = resp.read()
    return parse_splits_html(html_bytes)
